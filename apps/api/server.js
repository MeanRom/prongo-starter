// Counts visits. Uses Postgres when DATABASE_URL is set, otherwise memory (so `npm start` works locally).
import http from 'node:http'
import pg from 'pg'

const PORT = Number(process.env.PORT ?? 8080)

let pool
if (process.env.DATABASE_URL) {
  // {{ database.url }} is http://database.<project>.internal: we only need its hostname.
  pool = new pg.Pool({
    host: new URL(process.env.DATABASE_URL).hostname,
    user: 'postgres',
    password: process.env.POSTGRES_PASSWORD, // generated by Prongo on the first deploy
    database: 'postgres',
  })
  await pool.query('CREATE TABLE IF NOT EXISTS visits (id serial PRIMARY KEY, at timestamptz DEFAULT now())')
}

let memory = 0
async function visit() {
  if (!pool) return { visits: ++memory, store: 'memory' }
  await pool.query('INSERT INTO visits DEFAULT VALUES')
  const { rows } = await pool.query('SELECT count(*)::int AS n FROM visits')
  return { visits: rows[0].n, store: 'postgres' }
}

http
  .createServer(async (req, res) => {
    if (req.url === '/health') return res.end('ok')
    try {
      res.setHeader('content-type', 'application/json')
      res.end(JSON.stringify(await visit()))
    } catch (err) {
      res.statusCode = 500
      res.end(JSON.stringify({ error: String(err.message) }))
    }
  })
  .listen(PORT, () => console.log(`api on :${PORT}`))
